# Uebersetzer
# ---------------------------------------------------------------------------
_IDX = {"de": 1, "en": 2, "tr": 3}
_PH = re.compile(r"\{(\d+)\}")
_compiled = {}          # sprache -> [(regex, reihenfolge der platzhalter, zieltext)]
_missing = set()
MISSING_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "nexus_lang_missing.log")


def _unbrace(s):
    return s.replace("{{", "{").replace("}}", "}")


def _compile(lang):
    regeln = []
    for rule in RULES:
        src, tgt = rule[0], rule[_IDX[lang]]
        if tgt == src:
            continue
        teile = _PH.split(src)                      # text, nr, text, nr, ... , text
        literal = "".join(teile[0::2])
        if len(re.findall(r"[^\W\d_]", literal)) < 3:
            continue                                # zu wenig fester Text - wuerde ueberall passen
        rx, order = "", []
        for i, t in enumerate(teile):
            if i % 2 == 0:
                rx += re.escape(_unbrace(t))
            else:
                order.append(int(t))
                letzter = (i == len(teile) - 2 and teile[-1] == "")
                rx += "([^\\n]*)" if letzter else "([^\\n]*?)"
        if not order and len(literal.strip()) < 14:
            # kurzer fester Text: nur als ganzes Wort / ganze Wortgruppe ersetzen
            # Grenze nur dort, wo der Text selbst mit einem Buchstaben anfaengt / aufhoert
            # ("Kayit hatasi: " endet auf ein Leerzeichen - danach DARF ein Wort folgen)
            kern = _unbrace(literal)
            if re.match(r"[^\W\d_]", kern[:1] or " "):
                rx = r"(?<![^\W\d_])" + rx
            if re.match(r"[^\W\d_]", kern[-1:] or " "):
                rx = rx + r"(?![^\W\d_])"
        regeln.append((len(literal), re.compile(rx), order, tgt))
    regeln.sort(key=lambda r: -r[0])                # laengster fester Text zuerst
    return [(r[1], r[2], r[3]) for r in regeln]


def _ersetzer(order, tgt):
    def f(m):
        try:
            args = [""] * (max(order) + 1 if order else 0)
            for k, nr in enumerate(order):
                args[nr] = m.group(k + 1)
            return tgt.format(*args)
        except Exception:
            return m.group(0)
    return f


def translate(text, lang):
    """Text in die Sprache uebersetzen. Unbekannte Teile bleiben, wie sie sind."""
    if lang not in _IDX or not isinstance(text, str) or not text:
        return text
    if lang not in _compiled:
        _compiled[lang] = _compile(lang)
    out, treffer = text, 0
    for rx, order, tgt in _compiled[lang]:
        out, n = rx.subn(_ersetzer(order, tgt), out)
        treffer += n
    if treffer == 0:
        _note_missing(text, lang)
    return out


def _note_missing(text, lang):
    """Texte merken, fuer die es keine Regel gab (zum Nachtragen). Nie mehr als 400 Zeilen."""
    kurz = " ".join(text.split())[:160]
    if len(re.findall(r"[^\W\d_]{3,}", kurz)) < 2 or kurz.startswith("TRADE:"):
        return
    key = (lang, re.sub(r"\d+(?:[.,]\d+)?", "#", kurz))
    if key in _missing or len(_missing) >= 400:
        return
    _missing.add(key)
    try:
        with open(MISSING_FILE, "a", encoding="utf-8") as f:
            f.write("%s | %s\n" % (lang, kurz))
    except Exception:
        pass


def selfcheck():
    """Platzhalter aller Regeln pruefen. Rueckgabe: Liste von Fehlertexten."""
    fehler = []
    for n, rule in enumerate(RULES):
        if len(rule) != 4:
            fehler.append("Regel %d: braucht 4 Texte (Quelle, de, en, tr)" % n)
            continue
        soll = sorted(_PH.findall(rule[0]))
        for lang, i in _IDX.items():
            if sorted(_PH.findall(rule[i])) != soll:
                fehler.append("Regel %d (%s): Platzhalter stimmen nicht: %r" % (n, lang, rule[i][:60]))
            try:
                rule[i].format(*["x"] * (len(soll) + 1))
            except Exception as e:
                fehler.append("Regel %d (%s): %s" % (n, lang, e))
    for lang in LANGS:
        for name, _ in menu_commands(lang):
            if not re.fullmatch(r"[a-z0-9_]{1,32}", name):
                fehler.append("Befehlsname %r (%s): nur a-z, 0-9, _ erlaubt" % (name, lang))
    return fehler


if __name__ == "__main__":
    if len(sys.argv) >= 3:
        print(translate(sys.argv[2].replace("\\n", "\n"), sys.argv[1]))
    else:
        f = selfcheck()
        print("%d Regeln, %d Befehle, Sprachen: %s" % (len(RULES), len(COMMANDS), ", ".join(LANGS)))
        print("\n".join(f) if f else "OK - alle Platzhalter stimmen")
        sys.exit(1 if f else 0)
