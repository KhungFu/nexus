def command_names(main):
    """Alle Namen eines Befehls (Hauptname zuerst)."""
    c = COMMANDS.get(main)
    return [main] + [a for a in (c["alias"] if c else []) if a != main]


def menu_commands(lang):
    """[(name, beschreibung), ...] fuer das Telegram-Menue der Sprache."""
    return [(c["menu"].get(lang, main), c["desc"].get(lang, main)) for main, c in COMMANDS.items()]


def ai_hint(lang):
    return AI_HINT.get(lang, "")


